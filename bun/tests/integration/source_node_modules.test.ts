// A node_modules directory in the source tree (research G9 as corrected on
// 2026-10-21, US1-7, Edge Case): when REPO.bazel does not ignore it, it stays
// reachable through the execution root, under the sandbox and without one,
// and the load guard rejects every module in it; when
// ignore_directories(["**/node_modules"]) covers it, it is not reachable and
// the import fails with Bun's module-not-found error. Either way the package
// cannot be loaded (tasks.md T123). The same holds for an optional peer that
// nothing provides (US5-2, T091).

import { afterAll, expect, test } from "bun:test";
import { realpathSync } from "node:fs";
import { join } from "node:path";
import { rlocation } from "../support/spawn.ts";
import { assertOffline, Inner, INNER_TIMEOUT } from "./support/inner.ts";

const ARCHIVES = ["p@1.0.0", "phantom-user@1.0.0", "q@2.0.0"].map((p) =>
  rlocation(`_main/bun/tests/npm/registry/archives/${p}.tgz`),
);

const sessions: Inner[] = [];
afterAll(async () => {
  for (const inner of sessions) await inner.close();
});

type Case = {
  name: string;
  repo: string;
  expected: (sourceFile: (name: string) => string) => Record<string, string>;
};

const CASES: Case[] = [
  {
    name: "not ignored",
    repo: "",
    expected: (sourceFile) => ({
      phantom_test: `//:phantom_test: ${sourceFile("b")} is not declared by this target`,
      source_test: `//:source_test: ${sourceFile("b")} is not declared by this target`,
      optional_peer_test: `r did not load: @@//:optional_peer_test: ${sourceFile("r")} is not declared by this target`,
    }),
  },
  {
    name: "ignored",
    repo: 'ignore_directories(["**/node_modules"])\n',
    expected: () => ({
      phantom_test: "Cannot find module 'b'",
      source_test: "Cannot find package 'b'",
      optional_peer_test: "r did not load: Cannot find module 'r'",
    }),
  },
];

for (const { name, repo, expected } of CASES) {
  const inner = new Inner("source_nm", { npmArchives: ARCHIVES });
  sessions.push(inner);
  inner.write("REPO.bazel", repo);
  const sourceFile = (name: string) => join(realpathSync(inner.dir), "node_modules", name, "index.js");

  for (const strategy of [[], ["--spawn_strategy=local"]]) {
    test(
      `${name}, ${strategy.length ? "local" : "default"} strategy: b and r from the source node_modules do not load`,
      async () => {
        const result = await inner.run(["test", "//:all", "--test_output=errors", ...strategy]);
        // Bazel prints the test logs (--test_output=errors) on standard output.
        const output = result.stdout + result.stderr;
        console.log(output.split("\n").filter((l) => /error|declared|cannot find/i.test(l)).join("\n"));
        expect(result.exitCode).not.toBe(0);
        for (const [target, message] of Object.entries(expected(sourceFile))) {
          expect(output, target).toContain(message);
        }
        assertOffline(inner.log);
      },
      INNER_TIMEOUT,
    );
  }
}
